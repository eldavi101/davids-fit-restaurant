fun AlertWithReadStatus.toModel(): Alert = Alert(
    id = id,
    alertUid = alertUid,
    ticker = ticker,
    companyName = companyName,
    status = AlertStatus.from(status),
    strategyVersion = strategyVersion,
    buyTsUtc = buyTsUtc,
    buyPrice = buyPrice,
    opportunityScore = opportunityScore,
    confidence = confidence,
    probability = probability,
    probabilitySampleSize = probabilitySampleSize,
    expectedValue = expectedValue,
    rewardRisk = rewardRisk,
    marketRegime = marketRegime,
    sector = sector,
    industry = industry,
    breakoutType = breakoutType,
    stopPrice = stopPrice,
    currentStopPrice = currentStopPrice,
    trailingStopPrice = trailingStopPrice,
    target1Price = target1Price,
    target2Price = target2Price,
    currentPrice = currentPrice,
    currentReturnPct = currentReturnPct,
    maxGainPct = maxGainPct,
    maxDrawdownPct = maxDrawdownPct,
    remainingFraction = remainingFraction,
    thesisValid = thesisValid,
    thesisNotes = thesisNotes,
    buyReasons = buyReasons,
    riskFactors = riskFactors,
    componentScores = ComponentScores(
        trend = trendScore,
        momentum = momentumScore,
        volume = volumeScore,
        breakout = breakoutScore,
        relativeStrength = relativeStrengthScore,
        fundamental = fundamentalScore,
        risk = riskScore,
    ),
    closedTsUtc = closedTsUtc,
    finalReturnPct = finalReturnPct,
    holdingPeriodDays = holdingPeriodDays,
    sell = sellUid?.let {
        SellAlert(
            alertUid = it,
            buyAlertId = id,
            ticker = ticker,
            sellTsUtc = sellTsUtc ?: 0L,
            sellPrice = sellPrice ?: 0.0,
            entryPrice = buyPrice,
            fractionClosed = 1.0,
            finalReturnPct = finalReturnPct ?: 0.0,
            rMultiple = sellRMultiple ?: 0.0,
            holdingPeriodDays = holdingPeriodDays ?: 0,
            exitReason = sellReason.orEmpty(),
            exitReasonDetail = sellReasonDetail,
            maxGainPct = maxGainPct,
            maxDrawdownPct = maxDrawdownPct,
            strategyVersion = strategyVersion,
        )
    },
    fetchedAtUtc = fetchedAtUtc,
    isRead = isRead ?: false,
    isArchived = isArchived ?: false,
)

